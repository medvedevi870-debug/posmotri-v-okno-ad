# 1. Создайте папку проекта и перейдите в неё
mkdir hard-to-focus
cd hard-to-focus

# 2. Скопируйте все файлы выше в соответствующие папки

# 3. Инициализируйте git
git init

# 4. Добавьте все файлы
git add .

# 5. Сделайте коммит
git commit -m "initial commit: completed project"

# 6. Свяжите с удалённым репозиторием (замените user/repo на свои)
git remote add origin https://github.com/ВАШ_ЛОГИН/НАЗВАНИЕ_РЕПО.git

# 7. Запушьте
git push -u origin main